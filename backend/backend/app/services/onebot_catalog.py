COMPATIBILITY_ACTIONS = frozenset({"clean_stream_temp_file", "forward_msg"})


def _action(
    name: str,
    action: str,
    category: str,
    group: bool = False,
    *,
    execute_action: str | None = None,
    example: dict | None = None,
) -> dict:
    """构造接口中心动作目录项。

    预置动作可以通过 ``execute_action`` 映射到 NapCat 的真实 action，
    用于为同一个底层消息接口提供更易发现的图片、表情等参数示例。
    """
    actual_action = execute_action or action
    example = dict(example if example is not None else ACTION_EXAMPLES.get(actual_action, {}))
    if group:
        example.pop("group_id", None)
    item = {
        "name": name,
        "action": action,
        "category": category,
        "requires_group": group,
        "dangerous": actual_action in DANGEROUS_ACTIONS,
        "compatibility": actual_action in COMPATIBILITY_ACTIONS,
        "example": example,
    }
    if execute_action:
        item["execute_action"] = execute_action
    return item


